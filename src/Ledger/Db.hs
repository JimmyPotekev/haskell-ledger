-- ------------------------------------------------------------
-- Connection
-- ------------------------------------------------------------

loadConnectInfo :: IO ConnectInfo
loadConnectInfo = do
  envExists <- doesFileExist ".env"
  if envExists then loadFile defaultConfig >> pure () else pure ()
  host     <- getEnv "LEDGER_DB_HOST"
  portStr  <- getEnv "LEDGER_DB_PORT"
  user     <- getEnv "LEDGER_DB_USER"
  password <- getEnv "LEDGER_DB_PASSWORD"
  db       <- getEnv "LEDGER_DB_NAME"
  let port = case readMaybe portStr of
               Just n  -> n
               Nothing -> error ("LEDGER_DB_PORT not a number: " ++ portStr)
  pure defaultConnectInfo
    { connectHost     = host
    , connectPort     = port
    , connectUser     = user
    , connectPassword = password
    , connectDatabase = db
    }

-- Convenience: load config and open a connection in one go.
openConnection :: IO Connection
openConnection = loadConnectInfo >>= connect

