-- Accounts
-- ------------------------------------------------------------

-- Insert a new account by name. Returns the generated id.
-- RETURNING id is a Postgres thing that lets you grab the
-- autogenerated serial without a second round trip.
createAccount :: Connection -> Text -> IO AccountId
createAccount conn name = do
  rows <- query conn
    "INSERT INTO accounts (name) VALUES (?) RETURNING id"
    (Only name)
  case rows of
    [Only aid] -> pure (AccountId aid)
    _          -> error "createAccount: expected exactly one row back"

-- Look up an account's name by id. Returns Nothing if the
-- account doesn't exist. Handlers use this to turn a bogus
-- :id in the URL into a 404 instead of a successful empty
-- response.
fetchAccountName :: Connection -> AccountId -> IO (Maybe Text)
fetchAccountName conn aid = do
  rows <- query conn
    "SELECT name FROM accounts WHERE id = ?"
    (Only aid)
  case rows of
    [Only name] -> pure (Just name)
    _           -> pure Nothing

-- ------------------------------------------------------------
-- Transactions
-- ------------------------------------------------------------

-- The money-moving function. Takes a validated Transaction
-- (remember: if you have one of these, it already balances)
-- plus an optional idempotency key, writes everything inside
-- one Postgres transaction, and returns the new tx id.
--
-- The withTransaction call is what makes crashes safe. Either
-- all three inserts (one into transactions, N into entries)
-- land together, or none do. There is no world where one
-- entry gets written and the other doesn't.
--
-- Idempotency: the UNIQUE constraint on idempotency_key does
-- the real work. If a replay comes in with the same key, the
-- INSERT fails with a constraint violation, which we catch
-- and translate into "look up the original and return it."
insertTransaction
  :: Connection
  -> Maybe Text          -- optional idempotency key
  -> Transaction
  -> IO Int64
insertTransaction conn mKey tx =
  (withTransaction conn (doInsert mKey))
    `catch` handleReplay
  where
    doInsert key = do
      -- 1. Insert the transaction row, get its id back.
      [Only txId] <- query conn
        "INSERT INTO transactions (idempotency_key) VALUES (?) RETURNING id"
        (Only key)
      -- 2. Insert every entry, pointing at that tx id.
      mapM_ (insertEntry txId) tx.entries
      pure txId

    insertEntry txId e = execute conn
      "INSERT INTO entries (transaction_id, account_id, amount_cents) \
      \VALUES (?, ?, ?)"
      (txId, e.account, e.amount)

    -- If the insert hit the UNIQUE(idempotency_key) constraint,
    -- it's a replay. Look up the existing tx id and return
    -- that instead of raising.
    handleReplay err =
      case (mKey, constraintViolation err) of
        (Just key, Just (UniqueViolation "transactions_idempotency_key_key")) -> do
          rows <- query conn
            "SELECT id FROM transactions WHERE idempotency_key = ?"
            (Only key)
          case rows of
            [Only existing] -> pure existing
            _               -> throwIO err
        _ -> throwIO err

-- Look up a transaction's entry list by its id. Returns
-- Nothing if the tx doesn't exist. Used by GET /transactions/:id.
fetchTransaction :: Connection -> Int64 -> IO (Maybe [(AccountId, Money)])
fetchTransaction conn txId = do
  -- First check the transaction row itself exists. If we only
  -- queried entries, a tx with zero entries (shouldn't happen,
  -- but hypothetically) would look the same as a missing tx.
  txRows <- query conn
    "SELECT id FROM transactions WHERE id = ?"
    (Only txId) :: IO [Only Int64]
  case txRows of
    [] -> pure Nothing
    _  -> do
      es <- query conn
        "SELECT account_id, amount_cents FROM entries \
        \WHERE transaction_id = ? ORDER BY id"
        (Only txId)
      pure (Just es)

-- ------------------------------------------------------------
-- Reads
-- ------------------------------------------------------------

-- Sum of all signed entries for an account.
-- COALESCE handles the "account exists but has no entries"
-- case: SUM of zero rows is NULL in SQL, COALESCE turns that
-- into 0. Without it we'd have to deal with Maybe here.
fetchBalance :: Connection -> AccountId -> IO Money
fetchBalance conn aid = do
  rows <- query conn
    "SELECT COALESCE(SUM(amount_cents), 0)::bigint FROM entries WHERE account_id = ?"
    (Only aid)
  case rows of
    [Only n] -> pure (Money (fromIntegral (n :: Int64)))
    _        -> error "fetchBalance: expected exactly one row"

-- Every entry touching this account, newest first.
-- Returns (transaction_id, amount) tuples. Keeping it simple
-- for now; we can enrich with timestamp later if needed.
fetchHistory :: Connection -> AccountId -> IO [(Int64, Money)]
fetchHistory conn aid = query conn
  "SELECT transaction_id, amount_cents \
  \FROM entries \
  \WHERE account_id = ? \
  \ORDER BY id DESC"
  (Only aid)

